const englishToHindi = Object.fromEntries(
  Object.entries(hindiToEnglish).map(([hindi, english]) => [english, hindi]),
);

const dynamicContent = "#school-results, #school-detail, #my-report-results, #dashboard-stats, #category-stats, #admin-reports, #transcript";

function translateDictionary(language) {
  return language === "en" ? hindiToEnglish : englishToHindi;
}

function replaceText(text, dictionary) {
  const trimmed = text.trim();
  const replacement = dictionary[trimmed];
  if (!replacement) return text;
  const start = text.indexOf(trimmed);
  return `${text.slice(0, start)}${replacement}${text.slice(start + trimmed.length)}`;
}

export function applyStaticTranslations(language) {
  const dictionary = translateDictionary(language);
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement.closest(dynamicContent) || node.parentElement.closest(".user-message")) continue;
    node.nodeValue = replaceText(node.nodeValue, dictionary);
  }

  for (const element of document.querySelectorAll("[placeholder], [aria-label]")) {
    for (const attribute of ["placeholder", "aria-label"]) {
      if (element.hasAttribute(attribute)) {
        element.setAttribute(attribute, replaceText(element.getAttribute(attribute), dictionary));
      }
    }
  }

  document.documentElement.lang = language;
  document.title = language === "en"
    ? "School360 Voice — Speak. Discover. Report. Improve."
    : "School360 Voice — बोलें। खोजें। रिपोर्ट करें। सुधारें।";
  document.querySelector('meta[name="description"]').content = language === "en"
    ? "Speak, discover government schools, and report infrastructure issues with School360 Voice."
    : "School360 Voice के साथ सरकारी स्कूल खोजें और सुविधाओं की समस्याएँ बोलकर दर्ज करें।";
}
